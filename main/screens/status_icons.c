/*
 * status_icons.c - see status_icons.h. Pixel data generated (28x28,
 * LV_COLOR_FORMAT_A8 alpha-only bitmaps - tinted at draw time via
 * lv_obj_set_style_image_recolor(), same as every other status icon's
 * text-color convention in status_bar.c) from user-provided source art:
 * assets/ui/satellite.png (GNSS) and assets/ui/network.png (LoRa/mesh) -
 * both transparent-background black line art, alpha channel used directly
 * as the coverage map, tight-cropped to content then downsampled.
 *
 * Downsampling the 512x512 source straight to 28x28 (plain area-average
 * resize) leaves most line pixels only partially covered - the source
 * lines are only a couple of px wide, so at this ratio a typical line
 * pixel's cell is mostly background. That diluted the alpha map (nonzero
 * mean ~93/255 for the satellite icon) and made the tinted icon render as
 * a faded, off-color wash instead of a solid color like every other status
 * icon (montserrat glyphs don't thin out the same way at this size) -
 * reported live as "color of satellite symbol is kinda off". Fixed by a
 * threshold ramp applied to the resized alpha map before quantizing to A8:
 * alpha >= 70 saturates to 255, anything below ramps linearly - real
 * line coverage reads fully opaque (tinted solid, as intended), only the
 * genuine edge anti-aliasing stays soft. Same technique applied to both
 * icons for consistency.
 */
